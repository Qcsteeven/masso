def ext(d, cid, x, y, w, h, name):
    return d.box(cid, x, y, w, h, name, rounded=False, size=13, stroke=2)


def lab(d, x, y, w, html, align="center", h=None):
    """Side caption without background (not on a line)."""
    lines = html.count("<br>") + 1
    h = h or 15 * lines + 2
    if align == "right":
        d.text(None, x - w, y - h / 2, w, h, html, size=10, align="right")
    elif align == "left":
        d.text(None, x, y - h / 2, w, h, html, size=10, align="left")
    else:
        d.label(x, y, w, html, size=10)


