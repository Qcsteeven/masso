    d.call("be", "sm", "pause(container_id) — для учебного сервера")
    d.call("sm", "dk", "POST /containers/{id}/pause")
    d.reply("dk", "sm", "204")
    d.reply("sm", "be", "OK")
    d.call("be", "db", "UPDATE sessions (paused, paused_at)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 {status: paused}")
