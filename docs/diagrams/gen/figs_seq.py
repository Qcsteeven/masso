@fig
def fig19_code_task():
    d = Seq("fig19_code_task", maxw=MW)
    d.actor("st", "Обучающийся")
    d.part("fe", "Frontend (SPA)")
    d.part("be", "Backend: /api/sessions")
    d.part("ve", "Verification Engine")
    d.part("cr", "CodeRunner (app/coderun)")
    d.part("dk", "Docker Engine")
    d.part("db", "PostgreSQL")
    # autosave
    d.call("st", "fe", "Изменить solution.py или test_solution.py (редактор CodeMirror 6)")
    d.call("fe", "be", "POST /api/sessions/{id}/answers {files} — через 1,5 с после изменения")
    d.call("be", "db", "UPDATE sessions.documents_state (answers.files); INSERT environment_events (answer)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 {answers} (422 VALIDATION_ERROR: чужое имя файла или > 32 000 символов)")
    d.reply("fe", "st", "«Сохранено в …»")
    # run
    d.call("st", "fe", "Запустить тесты")
    d.call("fe", "be", "POST /api/sessions/{id}/run {files}")
    d.alt("сессия не активна")
    d.reply("be", "fe", "409 SESSION_NOT_READY")
    d.else_("с прошлого запуска прошло меньше 3 с")
    d.reply("be", "fe", "422 VALIDATION_ERROR {retry_after_sec}")
    d.else_("запуск разрешен")
    d.call("be", "cr", "run_cases(solution, examples, 5 с); run_student_tests(tests, 10 с)")
    d.call("cr", "dk", "POST /containers/create, start: образ песочницы, Cmd sleep infinity, user student, network none, cap_drop ALL, read-only, 1 CPU, 512 МБ, 64 pids, kind=validation")
    d.reply("dk", "cr", "container_id")
    d.call("cr", "dk", "exec: файлы в /srv/task; сценарий проверки с входами примеров, затем test_* обучающегося")
    d.reply("dk", "cr", "Выводы функции и результаты тестов (после маркера)")
    d.self_("cr", "Сравнить с ожидаемыми ответами примеров")
    d.call("cr", "dk", "DELETE /containers/{id}?force&v")
    d.reply("dk", "cr", "204")
    d.reply("cr", "be", "Примеры N из M, тесты K из L, stdout")
    d.call("be", "db", "UPDATE documents_state (код сохранен); INSERT environment_events (command «запуск: примеры N из M, тесты K из L»)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 {examples, tests, stdout, retry_after_sec: 3}")
    d.end()
    d.reply("fe", "st", "Результаты примеров и собственных тестов; баллы не начисляются")
    # self-check
    d.call("st", "fe", "Проверить выполнение")
    d.call("fe", "be", "POST /api/sessions/{id}/self-check")
    d.call("be", "db", "SELECT sessions FOR UPDATE; время последней самопроверки")
    d.reply("db", "be", "Сессия, события check (self_check)")
    d.alt("с прошлой самопроверки прошло меньше 30 с")
    d.reply("be", "fe", "422 VALIDATION_ERROR {retry_after_sec}")
    d.else_("самопроверка разрешена")
    d.call("be", "ve", "run_checks(spec, сохраненные файлы)")
    d.call("ve", "cr", "Проверки code_cases и code_student_tests в одной песочнице, как при отправке")
    d.reply("cr", "ve", "Результаты; контейнер удален")
    d.reply("ve", "be", "passed / failed / skipped по каждой проверке")
    d.self_("be", "Оставить только названия критериев и результат, без параметров и весов")
    d.call("be", "db", "INSERT environment_events (check, self_check: N из M)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 {results [{title, passed, skipped}], passed, total, retry_after_sec: 30}")
    d.end()
    d.reply("fe", "st", "Критерии: выполнен / не выполнен / ждет инцидента; балл не снижается")
    # submit
    d.call("st", "fe", "Завершить и отправить")
    d.call("fe", "be", "POST /api/sessions/{id}/submit (перед ним /answers, если есть несохраненные изменения)")
    d.call("be", "db", "UPDATE sessions (checking, finished_at)")
    d.reply("db", "be", "OK")
    d.call("be", "ve", "AssessmentAgent: run_checks(spec, файлы)")
    d.call("ve", "cr", "box(): одна песочница на все проверки")
    d.call("cr", "dk", "POST /containers/create, start (sleep infinity, те же флаги, kind=validation)")
    d.reply("dk", "cr", "container_id")
    d.loop("code_cases по группам: examples, basic, edge, perf (лимит времени), incident — если инцидент наступил")
    d.call("ve", "cr", "check_cases(group, time_limit)", act=False)
    d.call("cr", "dk", "exec: solution.py и входы группы; ожидаемые ответы в контейнер не передаются")
    d.reply("dk", "cr", "Выводы функции (для больших данных — хеш SHA-256)")
    d.self_("cr", "Сравнить с эталоном, вычисленным на backend (для perf — по хешу)")
    d.reply("cr", "ve", "Верно N из M или ошибка, тайм-аут", act=False)
    d.end()
    d.call("ve", "cr", "check_student_tests(min_killed = 2)", act=False)
    d.call("cr", "dk", "exec: тесты обучающегося на эталонном решении")
    d.reply("dk", "cr", "Все тесты проходят?")
    d.loop("для каждого мутанта — типичной ошибки")
    d.call("cr", "dk", "exec: тесты обучающегося на мутанте")
    d.reply("dk", "cr", "Тест упал — ошибка найдена")
    d.end()
    d.reply("cr", "ve", "Найдено K из L ошибок (нужно не менее 2)", act=False)
    d.call("cr", "dk", "Выход из box: DELETE /containers/{id}?force&v")
    d.reply("dk", "cr", "204")
    d.reply("cr", "ve", "Песочница удалена")
    d.reply("ve", "be", "Результаты проверок code_cases, code_student_tests")
    d.call("be", "db", "Балл, навыки и отчет (рис. 14): INSERT verification_results, reports; UPDATE sessions (completed)")
    d.reply("db", "be", "report_id")
    d.reply("be", "fe", "200 {report_id, status: completed, score}")
    d.reply("fe", "st", "Протокол прохождения")
    d.build(OUT + "fig19_code_task.drawio")


