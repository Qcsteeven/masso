    d.actor("m", "Методист")
    d.part("fe", "Frontend (SPA)")
    d.part("be", "Backend: /api/skills, /api/scenarios")
    d.part("sa", "ScenarioAgent")
    d.part("sm", "Sandbox Manager")
    d.part("db", "PostgreSQL")
    d.opt("новая предметная область")
    d.call("m", "fe", "«+ Домен»: код, название, описание")
    d.call("fe", "be", "POST /api/skills/domains")
    d.call("be", "db", "INSERT domains; INSERT audit_logs (domain.create)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "201 домен")
    d.reply("fe", "m", "Домен добавлен")
    d.end()
    d.call("m", "fe", "Добавить навык: описание, теория (Markdown), prerequisite-связи")
    d.call("fe", "be", "POST /api/skills")
    d.call("be", "db", "INSERT skills (theory), skill_requires; проверка ацикличности; INSERT audit_logs (skill.create)")
    d.reply("db", "be", "skill_id или цикл (422 VALIDATION_ERROR)")
    d.reply("be", "fe", "201 навык")
    d.call("fe", "be", "PUT /api/skills/targets {domain, skill, required_level}")
    d.call("be", "db", "UPSERT track_targets; INSERT audit_logs")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 целевые уровни")
    d.reply("fe", "m", "Граф компетенций и целевые уровни")
    d.call("m", "fe", "Шаблон: легенда, сбои и пул инцидентов или документы, проверки, подсказки")
    d.call("fe", "be", "POST /api/scenarios/templates (PATCH при правке)")
    d.call("be", "db", "INSERT scenario_templates (draft), template_skills, audit_logs (template.create)")
    d.reply("db", "be", "template_id")
    d.reply("be", "fe", "201 шаблон")
    d.call("fe", "be", "POST /api/scenarios/templates/{id}/validate")
    d.call("be", "sa", "run(template, base=spec)")
    d.call("sa", "sm", "Прогон в контейнере validation: сбой и инциденты ломают проверки, исправление восстанавливает; для кода — эталон и типичные ошибки")
    d.reply("sm", "sa", "Результаты прогона")
    d.reply("sa", "be", "Статус и шаги валидации")
    d.call("be", "db", "UPDATE validation_report (status, version); INSERT audit_logs (template.validate)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 отчет валидации")
    d.reply("fe", "m", "Отчет валидации по шагам")
    d.call("m", "fe", "Опубликовать")
    d.call("fe", "be", "POST /api/scenarios/templates/{id}/publish")
    d.alt("текущая версия не прошла валидацию")
    d.reply("be", "fe", "422 SCENARIO_NOT_VALID")
    d.else_("валидация текущей версии пройдена")
    d.call("be", "db", "UPDATE status = published, published_at; INSERT audit_logs (template.publish)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 шаблон")
    d.end()
    d.reply("fe", "m", "Статус шаблона")
    d.build(OUT + "fig16_template.drawio")


