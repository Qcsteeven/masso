    d.call("gw", "db", "SELECT llm_settings")
    d.reply("db", "gw", "generation_mode")
    d.call("gw", "pr", "local: запрос к локальной модели; template: вызова нет")
    d.reply("pr", "gw", "Ответ модели")
    d.deactivate("gw")
    d.end()
    d.activate("tf")
    d.call("tf", "be", "GET /api/llm/status (каждые 60 с)")
    d.call("be", "db", "SELECT llm_settings")
    d.reply("db", "be", "Режим, время, причина")
    d.reply("be", "tf", "200 {generation_mode, updated_at, reason}")
    d.self_("tf", "Баннер «LLM-контур переключен»")
    d.deactivate("tf")
    d.build(OUT + "fig17_llm_switch.drawio")


