    d.call("gw", "pr", "GET {base_url}/models")
    d.reply("pr", "gw", "Ответ или ошибка")
    d.reply("gw", "be", "Задержки и ошибки")
    d.reply("be", "fe", "200 [{code, ok, latency_ms, error}]")
    d.reply("fe", "a", "Статусы провайдеров")
    d.call("a", "fe", "Выбрать режим local или template, указать причину")
    d.call("fe", "be", "POST /api/admin/llm/switch-mode {mode, reason}")
    d.call("be", "db", "UPDATE llm_settings (generation_mode, reason, updated_by); INSERT audit_logs (llm.switch_mode)")
    d.reply("db", "be", "OK")
    d.reply("be", "fe", "200 {generation_mode, updated_at, reason}")
    d.reply("fe", "a", "Режим изменен; активные сессии продолжаются")
    d.opt("следующая генерация легенды или подсказка")
