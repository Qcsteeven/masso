d = Diagram("fig20_conceptual")


def group(cid, x, y, title, items, w=520):
    h = 56 + 44 * len(items) + 12
    d.box(cid, x, y, w, h, "", rounded=False, dashed=True, fill=GRAY)
    d.text(None, x + 16, y + 10, w - 32, 26, f"<b>{title}</b>", size=14, align="left")
    for i, it in enumerate(items):
        d.box(None, x + 40, y + 56 + 44 * i, w - 80, 34, it, rounded=False, size=13)
    return y + h


